"""
Phase 11a: Export compact JS data for the HTML dashboard (real Kaggle dataset).
Output: dashboard/data.js  (window.PHARMA = {...})
Rows keep only [dateIdx, catIdx, units] — EUR measures are derived in the
browser from the same documented price/margin assumptions, so the JS totals
match the CSV exactly.
"""
import json
from pathlib import Path

import pandas as pd

BASE = Path(__file__).resolve().parents[1]
OUT = BASE / "dashboard" / "data.js"
OUT.parent.mkdir(exist_ok=True)

fact = pd.read_csv(BASE / "data" / "pharma_sales_fact.csv", parse_dates=["Date"])
hours = pd.read_csv(BASE / "data" / "hour_profile.csv")

dates = sorted(fact["Date"].unique())
d_idx = {d: i for i, d in enumerate(dates)}
WD = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]

codes = sorted(fact["ATCCode"].unique())
code_to_cat = fact.drop_duplicates("ATCCode").set_index("ATCCode")["Category"]
# stable category order by ATC code
cat_order = [code_to_cat[c] for c in codes]
c_idx = {name: i for i, name in enumerate(cat_order)}

rows = [[d_idx[d], c_idx[cat], round(float(u), 3)]
        for d, cat, u in zip(fact["Date"], fact["Category"], fact["Units"])]

cat_meta = (fact.drop_duplicates("ATCCode").set_index("ATCCode")
            .reindex(codes))
margin_rate = (cat_meta["MarginPct"] / 100).round(4)

piv = hours.pivot_table(index="Weekday", columns="Hour", values="AvgUnits")
piv = piv.reindex(WD).fillna(0.0)

payload = {
    "meta": {
        "rows": len(rows),
        "days": len(dates),
        "source": "Kaggle 'Pharma sales data' by Milan Zdravkovic (CC BY-NC 4.0)",
        "url": "https://www.kaggle.com/datasets/milanzdravkovic/pharma-sales-data",
        "range": [str(pd.Timestamp(dates[0]).date()), str(pd.Timestamp(dates[-1]).date())],
        "unitsTotal": round(float(fact["Units"].sum()), 1),
        "revTotal": round(float(fact["EstRevenue"].sum()), 0),
        "profitTotal": round(float(fact["EstGrossProfit"].sum()), 0),
        "generated": pd.Timestamp.today().strftime("%Y-%m-%d"),
    },
    "dates": [str(pd.Timestamp(d).date()) for d in dates],
    "years": [int(str(pd.Timestamp(d).year)) for d in dates],
    "dows": [WD.index(pd.Timestamp(d).day_name()) for d in dates],
    "catOrder": cat_order,
    "cats": [{"code": c, "name": n, "desc": dsc, "price": float(p), "margin": float(m)}
             for c, n, dsc, p, m in zip(codes, cat_order,
                                        cat_meta["TherapyArea"],
                                        cat_meta["UnitPrice"], margin_rate)],
    "weekDays": WD,
    "hours": list(range(24)),
    "hourAvg": [[round(float(piv.loc[w, h]), 2) for h in range(24)] for w in WD],
    "rows": rows,
}

js = ("// Auto-generated by scripts/03_export_dashboard_data.py — do not edit by hand.\n"
      "window.PHARMA = " + json.dumps(payload, separators=(",", ":")) + ";\n")
OUT.write_text(js, encoding="utf-8")

print(f"written: {OUT}  ({OUT.stat().st_size / 1024:.0f} KB)")
print(f"rows {len(rows):,} | dates {len(dates)} | cats {len(cat_order)} | "
      f"range {payload['meta']['range']}")
print("totals check: units", sum(r[2] for r in rows),
      "| est rev", round(sum(r[2] * payload['cats'][r[1]]['price'] for r in rows)))
